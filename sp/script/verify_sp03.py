from sympy import *
ok=lambda c,m: print(('OK  ' if c else 'FAIL'),m)
A=Matrix([[1,-2,2],[-2,-2,4],[2,4,-2]])
ok((A-2*eye(3)).det()==0,'sp3_1 det(A-2I)=0'); print('  detA(24-25 1(2) matrix)=',A.det())
C=A.cofactor_matrix(); ok(C[1,0]+C[1,1]+2*C[1,2]==-18 and Matrix([[1,-2,2],[1,1,2],[2,4,-2]]).det()==-18,'sp3_2 A21+A22+2A23=-18')
print('  cofactors row2:',C[1,0],C[1,1],C[1,2])
V=Matrix([[1,1,1,1],[1,2,4,8],[1,3,9,27],[1,-1,1,-1]]); Cv=V.cofactor_matrix()
ok(V.det()==-48,'sp3_2 vdm det=-48'); ok(Cv[2,1]+Cv[2,2]+Cv[2,3]==12,'sp3_2 A32+A33+A34=12'); print('  A31..A34',[Cv[2,j] for j in range(4)], ' A31+2A32+3A33+4A34=',Cv[2,0]+2*Cv[2,1]+3*Cv[2,2]+4*Cv[2,3])
W=V.copy(); W[2,:]=Matrix([[0,1,1,1]]); print('  replaced det',W.det())
A5=Matrix([[0,2,3,0],[0,4,5,0],[0,1,0,3],[2,0,1,3]]); C5=A5.cofactor_matrix()
ok(A5.det()==12 and A5.adjugate().det()==1728,'sp3_4 det 12, adj 1728'); ok(C5[0,0]+C5[1,0]-C5[2,0]+2*C5[3,0]==6,'sp3_2 A11+A21-A31+2A41=6')
W=A5.copy(); W[:,0]=Matrix([1,1,-1,2]); print('  col-replaced det',W.det(), ' M41=',A5.minor(3,0))
A4=Matrix([[0,1,2,3],[1,1,1,1],[-2,-2,3,3],[1,2,-2,-3]]); ok(A4.det()==10,'sp3_3 detA=10')
B1=Matrix([[0,1,2,3],[-2,-2,3,3],[1,2,-2,-3],[1,1,1,1]]);B2=Matrix([[0,1,2,3],[1,1,1,1],[-1,-1,4,4],[2,3,-1,-2]])
B=B1+B2; ok(B.det()==40 and B1.det()+B2.det()==20,'sp3_3 detB=40, detB1+detB2=20'); print('  detB1,detB2',B1.det(),B2.det())
r=[A4.row(i) for i in range(4)]; ok(B.row(0)==2*r[0] and B.row(1)==r[1]+r[2] and B.row(2)==r[1]+r[2]+r[3] and B.row(3)==2*r[1]+r[3],'sp3_3 B rows')
M=A4.copy(); M.row_swap(0,1); M[2,:]+=2*M[0,:]; M[3,:]-=M[0,:]; M[3,:]-=M[1,:]; M[3,:]+=M[2,:]; print('  elim',M.tolist())
AA=Matrix([[1,1,1],[2,-1,0],[1,0,1]]); BB=Matrix([[1,0,0],[2,1,0],[0,2,1]]); ok((AA*BB+eye(3))==Matrix([[4,3,1],[0,0,0],[1,2,2]]),'sp3_5 AB+I'); print('  detA detB',AA.det(),BB.det(),' AB=',(AA*BB).tolist())
ok(Matrix([[2,2,1],[2,3,5],[2,5,3]]).det()==-20,'sp3_5 -20')
ok((2*eye(2)).det()==4,'sp3_6 det(2I)=4')
