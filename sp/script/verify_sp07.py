A=Matrix([[1,0],[0,0]]); B=Matrix([[1,0],[0,1]]); e=Matrix([1,0]); ok(A*e==B*e and A!=B,'Ax=Bx counterexample')
A=Matrix([[1,0],[0,0]]); B=Matrix([[0,0],[0,1]]); ok(A*B==A*zeros(2,2) and B!=zeros(2,2),'AB=AC counterexample')
